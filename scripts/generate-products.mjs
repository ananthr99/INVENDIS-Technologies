// Regenerates src/data/products.js, productImages.js, productDatasheets.js,
// and productUseCases.js from:
//   - src/content/products/*.json   (CMS-owned — name, specs, images, datasheet, use cases)
//   - src/data/productVariants.js   (developer-owned — free-form variant tables)
//
// This keeps every existing consumer (ProductSelector, ProductCard, ProductModal,
// FilterBar, the data-integrity tests, the sitemap generator) working completely
// unchanged — they still just import from src/data/products.js etc. as before;
// those files are now build artifacts instead of hand-maintained source.
//
// Run automatically via the predev/prebuild/pretest npm script hooks. Run by
// hand with: node scripts/generate-products.mjs

import { writeFileSync, readdirSync, readFileSync, mkdirSync } from 'fs'
import { fileURLToPath } from 'url'
import { dirname, join } from 'path'
import productVariants from '../src/data/productVariants.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const ROOT = join(__dirname, '..')
const CONTENT_DIR = join(ROOT, 'src/content/products')

mkdirSync(CONTENT_DIR, { recursive: true })

const files = readdirSync(CONTENT_DIR).filter(f => f.endsWith('.json')).sort()
const entries = files.map(f => JSON.parse(readFileSync(join(CONTENT_DIR, f), 'utf-8')))

if (entries.length === 0) {
  console.warn('⚠ No product files found in src/content/products/ — products.js will be empty.')
}

// ── products.js ──────────────────────────────────────────────────────────────
const products = entries.map(e => {
  const { images, datasheet, use_cases, ...flat } = e
  return { ...flat, variants: productVariants[e.id] || null }
})

writeFileSync(
  join(ROOT, 'src/data/products.js'),
  `// GENERATED FILE — do not edit by hand.\n` +
  `// Source of truth: src/content/products/*.json (CMS-managed) +\n` +
  `// src/data/productVariants.js (developer-managed). Regenerated by\n` +
  `// scripts/generate-products.mjs on every dev/build/test run.\n\n` +
  `const products = ${JSON.stringify(products, null, 2)}\n\n` +
  `export default products\n`
)

// ── productImages.js ─────────────────────────────────────────────────────────
const imagesObj = {}
entries.forEach(e => { if (e.images?.length) imagesObj[e.id] = e.images })

writeFileSync(
  join(ROOT, 'src/data/productImages.js'),
  `// GENERATED FILE — do not edit by hand. See products.js header.\n` +
  `const base = import.meta.env.BASE_URL\n\n` +
  `const productImages = {\n` +
  Object.entries(imagesObj)
    .map(([id, imgs]) => `  ${JSON.stringify(id)}: [${imgs.map(i => i.startsWith('http') ? JSON.stringify(i) : `\`\${base}${i.replace(/^\//, '')}\``).join(', ')}],`)
    .join('\n') +
  `\n}\n\n` +
  `export default productImages\n`
)

// ── productDatasheets.js ─────────────────────────────────────────────────────
const datasheetsObj = {}
entries.forEach(e => { if (e.datasheet) datasheetsObj[e.id] = e.datasheet })

writeFileSync(
  join(ROOT, 'src/data/productDatasheets.js'),
  `// GENERATED FILE — do not edit by hand. See products.js header.\n` +
  `// For per-variant/part-number datasheets, see the developer-managed\n` +
  `// src/data/partDatasheets.js instead.\n` +
  `const base = import.meta.env.BASE_URL\n\n` +
  `export const productDatasheets = {\n` +
  Object.entries(datasheetsObj)
    .map(([id, ds]) => `  ${JSON.stringify(id)}: ${ds.startsWith('http') ? JSON.stringify(ds) : `\`\${base}${ds.replace(/^\//, '')}\``},`)
    .join('\n') +
  `\n}\n`
)

// ── productUseCases.js ───────────────────────────────────────────────────────
const useCasesObj = {}
entries.forEach(e => { if (e.use_cases?.length) useCasesObj[e.id] = e.use_cases })

writeFileSync(
  join(ROOT, 'src/data/productUseCases.js'),
  `// GENERATED FILE — do not edit by hand. See products.js header.\n` +
  `const productUseCases = ${JSON.stringify(useCasesObj, null, 2)}\n\n` +
  `export default productUseCases\n`
)

console.log(`✓ Generated products.js, productImages.js, productDatasheets.js, productUseCases.js from ${entries.length} product files.`)
